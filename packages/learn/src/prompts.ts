// Prompts of the background experience review.
//
// Translated and adapted from Hermes Agent `agent/background_review.py`
// (catalogued in docs/research/prompts.md §7.1-7.4): the lesson shape, the
// "do not capture" block, the preference order and read-before-write keep the
// incidents that produced them, but the names and storage are DSHBOT's.
// The prompt goes into the review request only; it never becomes part of the
// stable prefix.

export interface ReviewContext {
  /** Last owner message of the turn that triggered the review. */
  userText: string
  /** Answer that was already delivered to the owner. */
  reply: string
  /** Current compact index, so the review sees what exists without a list call. */
  skillsIndex?: string
}

/** Stable first line of the review prompt; useful in logs. */
export const REVIEW_PROMPT_HEAD = 'Ты — фоновое ревью опыта DSHBOT.'

const LESSON_LAYER_BLOCK = `## Что такое навык

Навык — это инструкция, как выполнять класс задач самым правильным и коротким путём по меркам этого владельца: процедура, работающие инструменты и команды, их порядок, предпочтения владельца к результату и ловушки, которые стоили времени.

- Сначала процедура: шаги в том порядке, в каком их делают, с конкретными командами, вызовами инструментов и точками решений. Уроки и ловушки крепятся к шагу, к которому относятся.
- Ловушка — это общее правило плюс одна фраза «почему» (механизм), в повелительной форме. Не рассказ о том, что случилось в этой сессии.
- Ни номеров задач и PR, ни дат, ни цитат владельца как содержания: правило должно работать без истории, из которой оно родилось.
- Один и тот же урок, выученный дважды, — одно правило. Перед добавлением поищи уже сказанное в навыке и его файлах поддержки; усиль или уточни, а не добавляй вторую копию.
- Если навык врёт, исправь предложение на месте; не дописывай «UPDATE: на самом деле…».`

const DO_NOT_CAPTURE_BLOCK = `## Чего НЕ сохранять

- Отказы окружения: нет бинарника, ошибка свежей установки, несовпадение путей после переезда, «command not found», неподключённые учётки, неустановленные пакеты. Владелец может это исправить — это не долговечное правило.
- Отрицательные утверждения об инструментах и возможностях («браузер не работает», «инструмент X сломан», «Y нельзя вызвать из Z»). Они застывают в отказы, которые агент потом годами цитирует сам себе уже после починки.
- Временные ошибки сессии, которые решились до конца разговора. Если помог повтор, урок — это шаблон повтора, а не исходный сбой.
- Пересказ одной задачи: «сделал то-то для этого проекта» — не знание.
- Нерешённые неудачи: если рабочий способ так и не найден и владельцу предложено проверить вручную, НЕ записывай попытки как «надёжный процесс» или «рекомендованный подход».
- Если инструмент упал из-за состояния установки, сохраняй ИСПРАВЛЕНИЕ (команду установки, шаг конфигурации, переменную окружения) в существующем навыке про установку или разбор поломок, а не утверждение «этот инструмент не работает».`

const PREFERENCE_ORDER_BLOCK = `## Порядок действий

Предпочитай самое раннее действие, которое подходит, но выбери одно, если сигнал сработал:

1. Обнови навык, который уже загружен или прямо относится к классу задачи.
2. Обнови существующий зонтичный навык: сначала skills_list, затем skill_view.
3. Добавь файл поддержки под существующий зонтик.
4. Создай новый навык уровня класса, если ни один существующий не покрывает класс. Имя должно называть класс задач, а не сегодняшний случай.

Сигналы, которых достаточно для действия: владелец поправил стиль, тон, формат, подробность; поправил порядок или подход к работе; явно сказал «запомни»; повторяющаяся ошибка с понятным механизмом; найденный рабочий приём, который сэкономит время в следующий раз.

Read-before-write проверяется кодом: перед patch, write_file или remove_file существующего навыка вызови skill_view(name) в ЭТОМ ревью. Если запись отклонена с ошибкой read-before-write, вызови skill_view один раз и повтори запись один раз; не зацикливайся. Никогда не удаляй навык.`

const MEMORY_BLOCK = `## Память

Два разных хранилища, выбирай одно:

- target="user" (USER.md): кто такой владелец — характер, предпочтения, стиль общения и работы, личные детали, ожидания от поведения.
- target="memory" (MEMORY.md): факты об окружении, в котором ты работаешь — особенности инструментов, соглашения проекта, подводные камни конфигурации, важные пути и адреса.

Один факт — в одно хранилище, никогда в оба. Записи декларативные: «Владелец предпочитает короткие ответы», а не «Всегда отвечай коротко». Процедуры и ловушки для класса задач идут в навык, а не в память. Память вставляется в каждый ход и должна оставаться маленькой; при переполнении один пакет может удалить устаревшее и добавить новое.

Лишнее не сохраняй: тривиальные и очевидные факты, то, что легко переоткрыть, сырые дампы, прогресс задачи, журнал сделанного, временный TODO.`

/** Builds the one user message of the review. */
export function buildExperienceReviewPrompt(context: ReviewContext): string {
  const parts: string[] = [
    REVIEW_PROMPT_HEAD,
    '',
    'Разбери последний ход владельца и обнови библиотеку навыков или память, если это оправдано. Будь активен: большинство сессий дают хотя бы одно небольшое обновление, но «Nothing to save.» — честный и нормальный ответ, если сохранять действительно нечего.',
    '',
    LESSON_LAYER_BLOCK,
    '',
    DO_NOT_CAPTURE_BLOCK,
    '',
    PREFERENCE_ORDER_BLOCK,
    '',
    MEMORY_BLOCK,
    '',
    '## Как закончить',
    '',
    'Лимит — 16 итераций инструментов. В конце ответь коротким текстом: что обновил или почему ничего не сохранено. Если сохранять нечего, ответь ровно «Nothing to save.».',
    '',
    '## Материал для разбора',
    '',
    'Последнее сообщение владельца:',
    '<<<',
    context.userText,
    '>>>',
    '',
    'Доставленный ответ:',
    '<<<',
    context.reply,
    '>>>',
  ]
  if (context.skillsIndex !== undefined && context.skillsIndex.trim() !== '') {
    parts.push('', 'Текущий индекс навыков:', context.skillsIndex)
  }
  return parts.join('\n')
}
